// Utility functions
export const generateSeoHead = (pageData, additionalProps = {}) => {
  const {
    title,
    description,
    keywords,
    canonical,
    ogTitle,
    ogDescription,
    structuredData,
    noindex = false
  } = { ...pageData, ...additionalProps };

  return {
    title,
    description,
    keywords,
    canonical,
    ogTitle: ogTitle || title,
    ogDescription: ogDescription || description,
    structuredData,
    noindex
  };
};

